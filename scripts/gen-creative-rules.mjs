// Regenerates src/lib/creative-studio/rules.generated.ts from the rulebook
// .md files (the .md files are the source of truth — edit those, then run:
// node scripts/gen-creative-rules.mjs).
import { readFileSync, writeFileSync } from "node:fs";

const dir = "src/lib/creative-studio";
const kling = readFileSync(`${dir}/kling-framework.md`, "utf8");
const editing = readFileSync(`${dir}/editing-rules.md`, "utf8");
const story = readFileSync(`${dir}/story-rules.md`, "utf8");

const out = `// GENERATED by scripts/gen-creative-rules.mjs — do not edit by hand.
// Source: kling-framework.md, editing-rules.md and story-rules.md in this folder.

/** Marcel's Kling talking-head framework, verbatim. */
export const KLING_FRAMEWORK: string = ${JSON.stringify(kling)};

/** Marcel's Remotion editing rulebook, verbatim. */
export const EDITING_RULES: string = ${JSON.stringify(editing)};

/** Story videos (several scenes, any kind of shot): added after the framework for those videos only. */
export const STORY_RULES: string = ${JSON.stringify(story)};
`;
writeFileSync(`${dir}/rules.generated.ts`, out);
console.log("wrote", `${dir}/rules.generated.ts`, out.length, "bytes");
